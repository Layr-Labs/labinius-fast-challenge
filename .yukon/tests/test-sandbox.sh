#!/usr/bin/env bash
set -euo pipefail
umask 077

script_dir=$(cd "$(dirname "$0")/.." && pwd)
# shellcheck source=.yukon/lib/sandbox.sh
source "$script_dir/lib/sandbox.sh"

: "${RUNNER_TEMP:?RUNNER_TEMP is required}"
require_host_command /opt/cargo/bin/cargo
require_host_command /opt/cargo/bin/rustc
command -v bwrap >/dev/null

test_root=$(mktemp -d "$RUNNER_TEMP/labinius-sandbox-test.XXXXXX")
cleanup() {
  rm -rf "$test_root"
}
trap cleanup EXIT
ln -s / "$test_root/state-link"
if require_runner_temp_path "$test_root/state-link"; then
  echo "runner state accepted a symlink escape" >&2
  exit 1
fi

source_solution="$test_root/source/solution"
staged_solution="$test_root/staged/solution"
outside="$test_root/outside-secret"
mkdir -p "$source_solution/proof_generate/src"
printf 'host secret\n' > "$outside"
cat > "$source_solution/proof_generate/Cargo.toml" <<'CARGO'
[package]
name = "sandbox-smoke"
version = "0.1.0"
edition = "2021"
CARGO
cat > "$source_solution/proof_generate/Cargo.lock" <<'LOCK'
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "sandbox-smoke"
version = "0.1.0"
LOCK
cat > "$source_solution/proof_generate/src/main.rs" <<'RUST'
fn main() {
    assert!(std::env::var_os("LABINIUS_TEST_SECRET").is_none());
    println!("sandbox smoke");
}
RUST

python3 "$script_dir/stage-solution.py" "$source_solution" "$staged_solution"

symlink_source="$test_root/symlink-source"
mkdir -p "$symlink_source"
ln -s "$outside" "$symlink_source/escape"
if python3 "$script_dir/stage-solution.py" \
  "$symlink_source" "$test_root/symlink-destination"; then
  echo "stage-solution accepted a path-escape symlink" >&2
  exit 1
fi

target="$staged_solution/proof_generate/target"
cargo_home="$test_root/cargo-home"
mkdir -p "$target" "$cargo_home"

export LABINIUS_TEST_SECRET=must-not-cross-sandbox
run_contestant_build \
  "$staged_solution" \
  "$target" \
  "$cargo_home" \
  offline \
  /usr/bin/bash -c '
    set -euo pipefail
    test -z "${LABINIUS_TEST_SECRET+x}"
    test ! -e "$1"
    if touch /opt/cargo/bin/.labinius-host-write-test 2>/dev/null; then
      rm -f /opt/cargo/bin/.labinius-host-write-test
      echo "host tool directory was writable" >&2
      exit 1
    fi
    /opt/cargo/bin/cargo build --locked --offline
  ' bash "$outside"

if [[ -e /opt/cargo/bin/.labinius-host-write-test ]]; then
  rm -f /opt/cargo/bin/.labinius-host-write-test
  echo "sandbox planted a file in the host tool directory" >&2
  exit 1
fi
if [[ ! -x "$target/debug/sandbox-smoke" ]]; then
  echo "legitimate sandbox build did not produce its binary" >&2
  exit 1
fi
echo "sandbox regression tests passed"
