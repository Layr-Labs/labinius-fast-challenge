"""Writes ../src/ntt_neon_asm.rs: scheduled asm for pass_d and pass_c::<4> (prime 9721 schedule).
Run `python3 emit.py` here; the output is checked in, and tests compare it with the Rust passes."""
import os
os.environ['MFIRST'] = '1'
from sched import schedule, allocate
import gen_pd, gen_pc, gen_lut, re
def _masks(name):
    src = open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon.rs')).read()
    body = re.search(r'pub const %s: \[u16; 24\] = (\[[^\]]*\]);' % name, src).group(1)
    m = re.fullmatch(r'\[(\d+); 24\]', body)
    return [int(m.group(1))] * 24 if m else [int(x) for x in body.strip('[]').split(',')]
# the lazy reductions of levels 4 to 6 (`LAZY4`..`LAZY6` in src/ntt_neon.rs)
gen_pc.L4, gen_pc.L5, gen_pd.L6 = _masks('LAZY4'), _masks('LAZY5'), _masks('LAZY6')
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))
def pass_d(G=4, K=22, B=28):
    """Level 6 with the `LAZY6` reductions: the level-5 node pairs `q` grouped by their two
    first-input reductions, each class one loop of `G` groups (then a one-group loop for the rest),
    group addresses from the order table, so the code stays small (no per-pair unrolling)."""
    classes = [(r0, r3) for r0 in (True, False) for r3 in (True, False)]
    order = []
    lines = ['"ldr q15, [{kp}]"']
    seg = 0
    regs = sorted({f'xg{g}' for g in range(G)} | {f'tg{g}' for g in range(G)})
    for cls in classes:
        qs = [q for q in range(108) if (gen_pd.reduces(q, 0), gen_pd.reduces(q, 1)) == cls]
        order += qs
        for width, count in ((G, len(qs) // G), (1, len(qs) % G)):
            if count == 0:
                continue
            ins, low = gen_pd.build(width, cls=cls)
            seq, _ = schedule(ins, skew=K, budget=B)
            asm, _ = allocate(seq, {'k': 15}, low)
            lines += [f'"mov {{n}}, #{count}"', f'"{2 + seg}:"']
            for g in range(width):
                lines += [f'"ldrb {{tg{g}:w}}, [{{o}}], #1"', f'"add {{xg{g}}}, {{tg{g}}}, {{tg{g}}}, lsl #1"',
                          f'"add {{xg{g}}}, {{x}}, {{xg{g}}}, lsl #5"', f'"add {{tg{g}}}, {{t}}, {{tg{g}}}, lsl #4"']
            body = [a for a in asm]
            for g in range(width):
                body = [a.replace(f'XG{g}', f'{{xg{g}}}').replace(f'TG{g}', f'{{tg{g}}}') for a in body]
            lines += [f'"{a}"' for a in body]
            lines += ['"subs {n}, {n}, #1"', f'"b.ne {2 + seg}b"']
            seg += 1
    assert sorted(order) == list(range(108))
    body = ',\n        '.join(lines)
    outs = '\n'.join(f'        {r} = out(reg) _,' for r in regs)
    table = ', '.join(str(q) for q in order)
    return f"""/// The level-5 node pairs of [`pass_d_asm`] by reduction class (`LAZY6`).
static PASS_D_ORDER: [u8; 108] = [{table}];

/// Level 6 of prime 9721's table-fed transform with the first-input reductions of `LAZY6`,
/// generated by `gen/emit.py`: per reduction class a list-scheduled loop of {G} node pairs, the
/// pairs' addresses from [`PASS_D_ORDER`]. Every pair is independent, so the order is free.
#[inline(never)]
pub unsafe fn pass_d_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
        t = in(reg) kern.d.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        o = inout(reg) PASS_D_ORDER.as_ptr() => _,
        n = out(reg) _,
{outs}
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_c(per=6, K=40, B=28):
    body = gen_pc.emit(per, K, B).replace('",\n"', '",\n        "').rstrip(',')
    return f"""/// [`pass_c`]`::<4>` (levels 4 and 5 after the 9721 table front, the node reductions of
/// [`lut_node_kind`]) as straight-line list-scheduled code, generated by `gen/emit.py`; the same
/// instructions as the Rust pass, so the same values.
#[inline(never)]
pub unsafe fn pass_c_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
        c = in(reg) kern.c.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_lut(per=27, K=12, B=18, width=6, ls=1):
    body = gen_lut.emit(per, K, B, width, ls)
    bases = '\n'.join(f'        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128 * m}),' for m in sorted(gen_lut.BASES))
    return f"""/// [`pass_lut`]`::<1>` (levels 0 to 3 of the 9721 binary transform from the nibble tables) as
/// straight-line list-scheduled code, generated by `gen/emit.py`: node `n`'s six tables stay in
/// v16-v27; the same instructions as the Rust pass, so the same values. `idx` is packed
/// ([`packed_slot`]): each `ld1b {{z.h}}` zero-extends one slot's eight byte nibbles.
#[inline(never)]
pub unsafe fn pass_lut_asm(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
{bases}
        lut = in(reg) kern.lut.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        out("p7") _,
        options(nostack)
    );
}}
"""
out = "// Generated by gen/emit.py. Do not edit by hand.\nuse super::*;\n\n" + pass_d() + "\n" + pass_c() + "\n" + pass_lut()
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_asm.rs'), 'w').write(out)
