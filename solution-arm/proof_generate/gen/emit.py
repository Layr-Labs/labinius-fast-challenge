"""Writes ../src/ntt_neon_asm.rs: scheduled asm for pass_d and pass_c::<4> (prime 9721 schedule).
Run `python3 emit.py` here; the output is checked in, and tests compare it with the Rust passes."""
import os
os.environ['MFIRST'] = '1'
from sched import schedule, allocate
import gen_pd, gen_pc, gen_lut
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))
def pass_d(U=12, K=22, B=29):
    ins, low = gen_pd.build(U)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"']
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"', f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// [`pass_d`] (prime 9721: `FIRST13` inputs, no reduction of `d`) as one list-scheduled loop of
/// {U} groups, generated by `gen/emit.py`; the same instructions as the Rust pass, so the same values.
#[inline(never)]
pub unsafe fn pass_d_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_mut_ptr() => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_c(per=6, K=40, B=28):
    body = gen_pc.emit(per, K, B).replace('",\n"', '",\n        "').rstrip(',')
    return f"""/// [`pass_c`]`::<4>` (levels 4 and 5 after the 9721 table front, the node reductions of
/// [`lut_node_kind`]) as straight-line list-scheduled code, generated by `gen/emit.py`; the same
/// instructions as the Rust pass, so the same values.
#[inline(never)]
pub unsafe fn pass_c_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
        c = in(reg) kern.c.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_lut(per=27, K=12, B=18, width=6, ls=1):
    body = gen_lut.emit(per, K, B, width, ls)
    bases = '\n'.join(f'        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128 * m}),' for m in sorted(gen_lut.BASES))
    return f"""/// [`pass_lut`]`::<1>` (levels 0 to 3 of the 9721 binary transform from the nibble tables) as
/// straight-line list-scheduled code, generated by `gen/emit.py`: node `n`'s six tables stay in
/// v16-v27; the same instructions as the Rust pass, so the same values. `idx` is packed
/// ([`packed_slot`]): each `ld1b {{z.h}}` zero-extends one slot's eight byte nibbles.
#[inline(never)]
pub unsafe fn pass_lut_asm(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
{bases}
        lut = in(reg) kern.lut.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        out("p7") _,
        options(nostack)
    );
}}
"""
def pass_d_out(U=12, K=22, B=29):
    """The same level-6 schedule as `pass_d`, reading `x` and writing `y` (out of place)."""
    ins, low = gen_pd.build(U, outp=True)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"', '"add {y2}, {y}, #1024"']
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("YPTR2", "{y2}").replace("YPTR", "{y}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"', f'"add {{y}}, {{y}}, #{96*U}"', f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// [`pass_d_asm`] out of place: the same instructions in the same order, reading `x` and writing
/// `y`, so the transform can run in an L1-resident scratch and only level 6 writes the sweep buffer.
#[inline(never)]
pub unsafe fn pass_d_out(x: &[int16x8_t; N], y: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y.as_mut_ptr() => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        y2 = out(reg) _,
        {CLOB},
        options(nostack)
    );
}}
"""

def _add_imm(dst, src, val):
    """`dst = src + val` as AArch64 adds of encodable immediates (imm12, optionally << 12)."""
    hi, lo = val >> 12, val & 4095
    out, cur = [], src
    if hi:
        assert hi < 4096
        out.append(f'"add {{{dst}}}, {{{cur}}}, #{hi}, lsl #12"'); cur = dst
    if lo or not out:
        out.append(f'"add {{{dst}}}, {{{cur}}}, #{lo}"')
    return out

def pass_d_t(U=12, K=22, B=29, tstride=96 * 16, name='pass_d_t', blocked=False):
    """The level-6 butterflies of `pass_d`, reading `x` and writing TRANSPOSED: slot k of the transform
    goes to `y + k * tstride` bytes (slot-major sweep layout, so the sink reads one sequential stream)."""
    ins, low = gen_pd.build(U, outp=True, tstride=tstride, blocked=blocked)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"']
    lines += _add_imm('y2', 'y', 36 * tstride)
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("YPTR2", "{y2}").replace("YPTR", "{y}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"'] + _add_imm('y', 'y', 6 * U * tstride) + [f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// Level 6 out of place into the TRANSPOSED (slot-major) sweep layout: slot `k` of this transform
/// is written to `y + k * {tstride // 16}` vectors. Same butterflies as [`pass_d_asm`].
#[inline(never)]
pub unsafe fn {name}(x: &[int16x8_t; N], y: *mut int16x8_t, kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        y2 = out(reg) _,
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_d_bp(U=12, K=22, B=29, tstride=97 * 16, name='pass_d_bp'):
    """Level 6 into the padded BLOCKED layout with `stp q` pairs: each iteration computes one pointer per
    64-byte-line block (18 per 12 groups, `4 * tstride` apart) so every pair store fits `stp`'s range."""
    ins, low = gen_pd.build(U, outp=True, tstride=tstride, blocked=True, pairs=True)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    nb = 6 * U // 4
    bs = 4 * tstride
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"']
    for k in range(1, nb):
        lines += _add_imm(f'bp{k}', 'y' if k == 1 else f'bp{k-1}', bs)
    def name_of(a):
        for k in range(nb - 1, 0, -1):
            a = a.replace(f'BP{k}X', f'{{bp{k}}}')
        return a.replace('BP0X', '{y}')
    lines += [f'"{name_of(a).replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"'] + _add_imm('y', 'y', nb * bs) + [f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    bps = '\n'.join(f'        bp{k} = out(reg) _,' for k in range(1, nb))
    return f"""/// Level 6 into the padded blocked sweep layout with `stp q` pairs (one pointer per line block).
#[inline(never)]
pub unsafe fn {name}(x: &[int16x8_t; N], y: *mut int16x8_t, kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
{bps}
        {CLOB},
        options(nostack)
    );
}}
"""
out = "// Generated by gen/emit.py. Do not edit by hand.\nuse super::*;\n\n" + pass_d() + "\n" + pass_c() + "\n" + pass_lut() + "\n" + pass_d_out() + "\n" + pass_d_bp()
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_asm.rs'), 'w').write(out)
