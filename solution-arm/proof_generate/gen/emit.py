"""Writes ../src/ntt_neon_asm.rs: scheduled asm for pass_d and pass_c::<4> (prime 9721 schedule).
Run `python3 emit.py` here; the output is checked in, and tests compare it with the Rust passes."""
import os
os.environ['MFIRST'] = '1'
from sched import schedule, allocate
import gen_pd, gen_pc, gen_lut, gen_tail
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))
def pass_d(U=12, K=22, B=29):
    ins, low = gen_pd.build(U)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"']
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"', f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// [`pass_d`] (prime 9721: `FIRST13` inputs, no reduction of `d`) as one list-scheduled loop of
/// {U} groups, generated by `gen/emit.py`; the same instructions as the Rust pass, so the same values.
#[inline(never)]
pub unsafe fn pass_d_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_mut_ptr() => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_c(per=6, K=40, B=28):
    body = gen_pc.emit(per, K, B).replace('",\n"', '",\n        "').rstrip(',')
    return f"""/// [`pass_c`]`::<4>` (levels 4 and 5 after the 9721 table front, the node reductions of
/// [`lut_node_kind`]) as straight-line list-scheduled code, generated by `gen/emit.py`; the same
/// instructions as the Rust pass, so the same values.
#[inline(never)]
pub unsafe fn pass_c_asm(x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
        c = in(reg) kern.c.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_lut(per=27, K=12, B=18, width=6, ls=1):
    body = gen_lut.emit(per, K, B, width, ls)
    bases = '\n'.join(f'        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128 * m}),' for m in sorted(gen_lut.BASES))
    return f"""/// [`pass_lut`]`::<1>` (levels 0 to 3 of the 9721 binary transform from the nibble tables) as
/// straight-line list-scheduled code, generated by `gen/emit.py`: node `n`'s six tables stay in
/// v16-v27; the same instructions as the Rust pass, so the same values. `idx` is packed
/// ([`packed_slot`]): each `ld1b {{z.h}}` zero-extends one slot's eight byte nibbles.
#[inline(never)]
pub unsafe fn pass_lut_asm(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_mut_ptr(),
{bases}
        lut = in(reg) kern.lut.as_ptr(),
        kp = in(reg) kern.k.as_ptr(),
        {CLOB},
        out("p7") _,
        options(nostack)
    );
}}
"""
def pass_d_out(U=12, K=22, B=29):
    """The same level-6 schedule as `pass_d`, reading `x` and writing `y` (out of place)."""
    ins, low = gen_pd.build(U, outp=True)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"', '"add {y2}, {y}, #1024"']
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("YPTR2", "{y2}").replace("YPTR", "{y}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"', f'"add {{y}}, {{y}}, #{96*U}"', f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// [`pass_d_asm`] out of place: the same instructions in the same order, reading `x` and writing
/// `y`, so the transform can run in an L1-resident scratch and only level 6 writes the sweep buffer.
#[inline(never)]
pub unsafe fn pass_d_out(x: &[int16x8_t; N], y: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y.as_mut_ptr() => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        y2 = out(reg) _,
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_lut_loop(per=27, K=6, B=23, width=6, ls=1, cap=20):
    body = gen_lut.emit_loop(per, K, B, width, ls, cap=cap)
    bases = '\n'.join(f'        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128 * m}),' for m in sorted(gen_lut.BASES))
    return f"""/// [`pass_lut_asm`] as a 4-iteration loop over the level-3 nodes (the same per-node operations;
/// nodes differ only in the table and output bases), ~5 KB of code instead of ~19 KB. Rescheduled
/// with the five table registers the one-register lookups free (live budget 23, register cap 20, skew 6).
#[inline(never)]
pub unsafe fn pass_lut_loop(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_mut_ptr() => _,
{bases}
        lut = inout(reg) kern.lut.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        {CLOB},
        out("p7") _,
        options(nostack)
    );
}}
"""
def pass_tail(K=8, B=26):
    body = ',\n        '.join(gen_tail.emit_straight(K, B))
    return f"""/// [`pass_c_asm`] then [`pass_d_out`] fused per level-3 node (`gen/gen_tail.py`): the node's 27
/// values stay in registers from levels 4 to 6, read from `x` once and written to `y` once; the
/// same instructions on the same operands as the two passes, so the same values.
#[inline(never)]
pub unsafe fn pass_tail(x: &[int16x8_t; N], y: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = in(reg) x.as_ptr(),
        y = in(reg) y.as_mut_ptr(),
        c = in(reg) kern.c.as_ptr(),
        t = in(reg) kern.t6.as_ptr(),
        kc = in(reg) kern.kc.as_ptr(),
        {CLOB},
        options(nostack)
    );
}}
"""
def pass_tail_calls(K=8, B=26, name="pass_tail_calls", reserve=1, width=6, ls=2, mfirst=True):
    # the scheduler reads MFIRST per call: off selects its load-first priority order
    saved = os.environ.pop('MFIRST', None)
    if mfirst: os.environ['MFIRST'] = saved or '1'
    body = ',\n        '.join(gen_tail.emit_calls(K, B, reserve, width, ls))
    if saved is not None: os.environ['MFIRST'] = saved
    return f"""/// [`pass_tail`] with one body per node reduction kind ({len(gen_tail.kinds())} kinds), called per node
/// with the node's base pointers: about a third of the straight-line code (schedule skew {K},
/// live budget {B}, register reserve {reserve}).
#[inline(never)]
pub unsafe fn {name}(x: &[int16x8_t; N], y: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y.as_mut_ptr() => _,
        c = inout(reg) kern.c.as_ptr() => _,
        t = inout(reg) kern.t6.as_ptr() => _,
        kc = in(reg) kern.kc.as_ptr(),
        out("x30") _,
        {CLOB},
        options(nostack)
    );
}}
"""
out = "// Generated by gen/emit.py. Do not edit by hand.\nuse super::*;\n\n" + pass_d() + "\n" + pass_c() + "\n" + pass_lut() + "\n" + pass_d_out() + "\n" + pass_lut_loop() + "\n" + pass_tail() + "\n" + pass_tail_calls() + "\n" + pass_tail_calls(16, 28, "pass_tail_calls_b") + "\n" + pass_tail_calls(20, 29, "pass_tail_calls_c", 0, 5, 1, True)
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_asm.rs'), 'w', newline='').write(out.replace('\n', '\r\n'))
