"""Writes ../src/ntt_neon_asm_var.rs: the on-hardware tuning winners of pass_c / pass_lut as named
variants, for the in-context comparison (`sms::commit` gives each worker its own variant; diagnostic
only). Run `python3 emit_ctx.py` here."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import emit

PC = [(24, 40, 28, 6, 1), (6, 40, 28, 6, 1), (12, 40, 28, 6, 1)]
LUT = [(27, 8, 18, 6, 1), (9, 8, 18, 6, 1)]
out = ["// Generated by gen/emit_ctx.py. Diagnostic only (in-context variant comparison). Do not edit by hand.",
       "use super::*;", ""]
for i, p in enumerate(PC):
    out.append(emit.pass_c(*p, name=f'pass_c_var{i}'))
for i, p in enumerate(LUT):
    out.append(emit.pass_lut(*p, name=f'pass_lut_var{i}'))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'ntt_neon_asm_var.rs'), 'w').write('\n'.join(out) + '\n')

def pass_d_out(U=12, K=22, B=29, name='pass_d_out'):
    """The crown's level-6 schedule (same instructions, same order), reading `x` and writing `y`."""
    from sched import schedule, allocate
    import gen_pd
    ins, low = gen_pd.build(U, outp=True)
    seq, _ = schedule(ins, skew=K, budget=B)
    asm, _ = allocate(seq, {'k': 15}, low)
    lines = ['"ldr q15, [{kp}]"', f'"mov {{n}}, #{108 // U}"', '"2:"', '"add {x2}, {x}, #1024"', '"add {y2}, {y}, #1024"']
    lines += [f'"{a.replace("XPTR2", "{x2}").replace("XPTR", "{x}").replace("YPTR2", "{y2}").replace("YPTR", "{y}").replace("TPTR", "{t}")}"' for a in asm]
    lines += [f'"add {{x}}, {{x}}, #{96*U}"', f'"add {{y}}, {{y}}, #{96*U}"', f'"add {{t}}, {{t}}, #{16*U}"', '"subs {n}, {n}, #1"', '"b.ne 2b"']
    body = ',\n        '.join(lines)
    return f"""/// The crown's level 6 out of place: reads `x` (an L1-resident scratch), writes `y`. Diagnostic.
#[inline(never)]
pub unsafe fn {name}(x: &[int16x8_t; N], y: &mut [int16x8_t; N], kern: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y.as_mut_ptr() => _,
        t = inout(reg) kern.d.as_ptr() => _,
        kp = in(reg) kern.k.as_ptr(),
        n = out(reg) _,
        x2 = out(reg) _,
        y2 = out(reg) _,
        {emit.CLOB},
        options(nostack)
    );
}}
"""

with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'ntt_neon_asm_var.rs'), 'a') as fh:
    fh.write(pass_d_out() + '\n')
