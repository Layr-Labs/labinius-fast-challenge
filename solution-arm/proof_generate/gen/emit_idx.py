"""Writes ../src/ntt_neon_idx.rs: the scheduled index builder (gen_idx.py)."""
import os
import re
from sched import schedule, allocate
import gen_idx
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))
def indices(K=30, B=24):
    asm, cyc, n = [], 0, 0
    for P in (0, 1):
        ins = gen_idx.build(P)
        seq, c = schedule(ins, skew=K, budget=B, cap=28)
        a, _ = allocate(seq, dict(gen_idx.PIN), set(), reserved=())
        asm += a; cyc += c; n += len(ins)
    pro = ['"movi v28.16b, #0x0f", "movi v29.16b, #0x55"', '"movi v30.16b, #0x33"', '"movi v31.16b, #0"']
    lines = pro + [f'"{a.replace("IPTR", "{ix}")}"' for a in asm]
    lines = [re.sub(r'\[W(\d), #(\d+)\]', lambda m:
                    f'[{{w{m[1]}}}, #({{o{m[1]}}} + {m[2]})]', l) for l in lines]
    body = ',\n        '.join(lines)
    ws = '\n'.join(f'        w{c} = in(reg) $w{c}, o{c} = const $o{c},' for c in range(8))
    args = ', '.join(f'$w{c}:expr' for c in range(8))
    offs = ', '.join(f'$o{c}:expr' for c in range(8))
    ptrs = ', '.join(f'words[{c}]' for c in range(8))
    return f"""// Generated by gen/emit_idx.py. Do not edit by hand.
use super::*;

// One instruction schedule, with constant offsets for either independent lanes or two columns.
macro_rules! indices_body {{
    ($idx:expr, [{args}], [{offs}]) => {{
    core::arch::asm!(
        {body},
{ws}
        ix = in(reg) $idx.as_mut_ptr(),
        {CLOB},
        options(nostack)
    );
    }};
}}

/// [`indices`] for eight independent word pointers.
#[inline(never)]
pub unsafe fn indices_asm(words: &[*const u8; LANES], idx: &mut [uint8x16_t; GROUPS]) {{
    indices_body!(idx, [{ptrs}], [0, 0, 0, 0, 0, 0, 0, 0]);
}}

/// Four adjacent 64-byte elements in each of two columns. The lane order is unchanged.
/// The {n} vector instructions and {cyc}-cycle schedule are identical to [`indices_asm`].
#[inline(never)]
pub unsafe fn indices_contiguous(w0: *const u8, w1: *const u8, idx: &mut [uint8x16_t; GROUPS]) {{
    indices_body!(idx, [w0, w0, w0, w0, w1, w1, w1, w1], [0, 64, 128, 192, 0, 64, 128, 192]);
}}
"""
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_idx.rs'), 'w', newline='\r\n').write(indices())
