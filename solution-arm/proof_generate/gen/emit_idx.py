"""Writes ../src/ntt_neon_idx.rs: the scheduled index builder (gen_idx.py)."""
import os
from sched import schedule, allocate
import gen_idx
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))
def indices(K=30, B=24):
    asm, cyc, n = [], 0, 0
    for P in (0, 1):
        ins = gen_idx.build(P)
        seq, c = schedule(ins, skew=K, budget=B, cap=28)
        a, _ = allocate(seq, dict(gen_idx.PIN), set(), reserved=())
        asm += a; cyc += c; n += len(ins)
    pro = ['"movi v28.16b, #0x0f", "movi v29.16b, #0x55"', '"movi v30.16b, #0x33"', '"movi v31.16b, #0"']
    lines = pro + [f'"{a.replace("IPTR", "{ix}")}"' for a in asm]
    for c in range(8):
        lines = [l.replace(f'W{c},', f'{{w{c}}},') for l in lines]
    body = ',\n        '.join(lines)
    ws = '\n'.join(f'        w{c} = in(reg) words[{c}],' for c in range(8))
    return f"""// Generated by gen/emit_idx.py. Do not edit by hand.
use super::*;

/// [`indices`] (both word pairs) as straight-line list-scheduled code ({n} instructions,
/// {cyc} scheduled cycles), generated by `gen/emit_idx.py`; the same operations as the Rust
/// function, so the same indices.
#[inline(never)]
pub unsafe fn indices_asm(words: &[*const u8; LANES], idx: &mut [uint8x16_t; GROUPS]) {{
    core::arch::asm!(
        {body},
{ws}
        ix = in(reg) idx.as_mut_ptr(),
        {CLOB},
        options(nostack)
    );
}}
"""
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_idx.rs'), 'w').write(indices())
