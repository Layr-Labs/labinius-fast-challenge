"""Generate the signed role-band witness front and tail."""
import json
import os
from pathlib import Path

import gen_lut
import gen_tail
from sched import allocate, schedule

HERE = Path(__file__).resolve().parent
CLOB = ', '.join(f'out("v{r}") _' for r in range(32))


def front():
    lines = ['"ldr q15, [{kp}]"', '"ptrue p7.h"', '"mov {n}, #4"', '"3:"']
    for band in range(3):
        lines.append(f'"ldp q16, q17, [{{lut}}, #{192*band}]"')
        for t in range(1, 6):
            lines.append(f'"ldr q{16+2*t}, [{{lut}}, #{192*band+32*t}]"')
        ins = gen_lut.build_node(0, range(9*band, 9*(band+1)))
        seq, _ = schedule(ins, skew=6, budget=23, cap=20, width=6, ls=1)
        asm, _ = allocate(seq, {'k': 15}, set(), reserved=gen_lut.LOOP_RESERVED)
        lines.extend(f'"{gen_lut.base_names(a).replace("XPTR", "{x}").replace("LB", "{{").replace("RB", "}}")}"' for a in asm)
    lines += ['"add {x}, {x}, #2592"', '"add {lut}, {lut}, #576"', '"subs {n}, {n}, #1"', '"b.ne 3b"']
    body = ',\n        '.join(lines)
    bases = '\n'.join(f'        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128*m}),'
                      for m in sorted(gen_lut.BASES))
    return f'''
#[cfg(target_feature = "sve")]
#[inline(never)]
pub(super) unsafe fn front(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N], k: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_mut_ptr() => _,
{bases}
        lut = inout(reg) constants(k).lut.as_ptr() => _,
        kp = in(reg) k.k.as_ptr(),
        n = out(reg) _,
        {CLOB},
        out("p7") _,
        options(nostack)
    );
}}
'''


def tail():
    plans = [{} for _ in range(24)]
    for n, stage, block, off, mode, rotate, mask in json.loads((HERE / 'signed_plan.json').read_text()):
        plans[n][stage, block, off] = mode, rotate, mask
        if stage == 6:
            assert mask == 1 and not mode and not rotate
    bodies = []
    lines = []
    cycles = live = 0
    schedules = json.loads((HERE / 'signed_schedules.json').read_text())
    for n, (plan, (skew, budget, width, ls, reserve)) in enumerate(zip(plans, schedules)):
        asm, cyc, registers = gen_tail.node_asm(
            n, True, skew, budget, width, ls, reserve=reserve, signed_plan=plan)
        cycles += cyc
        live = max(live, registers)
        asm = [gen_tail.subst(a) for a in asm]
        if asm not in bodies:
            bodies.append(asm)
        lines += [f'"ldr q15, [{{kc}}, #{16*n}]"', f'"bl {20+bodies.index(asm)}f"',
                  '"add {x}, {x}, #432"', '"add {y}, {y}, #432"',
                  '"add {c}, {c}, #32"', '"add {t}, {t}, #80"']
    dynamic = sum(6 + len(gen_tail.build(n, True, plan)[0]) + 1 for n, plan in enumerate(plans))
    print('Tail bodies', len(bodies), 'static body instructions', sum(map(len,bodies)),
          'dynamic instructions', dynamic, 'cycles', cycles, 'max registers', live)
    lines.append('"b 9f"')
    for i, body in enumerate(bodies):
        lines += [f'"{20+i}:"', *(f'"{a}"' for a in body), '"ret"']
    lines.append('"9:"')
    body = ',\n        '.join(lines)
    return f'''
#[inline(never)]
pub(super) unsafe fn tail(x: &[int16x8_t; N], y: &mut [int16x8_t; N], k: &Kernel) {{
    core::arch::asm!(
        {body},
        x = inout(reg) x.as_ptr() => _,
        y = inout(reg) y.as_mut_ptr() => _,
        c = inout(reg) k.c.as_ptr() => _,
        t = inout(reg) k.t6.as_ptr() => _,
        kc = in(reg) constants(k).kc.as_ptr(),
        out("x30") _,
        {CLOB},
        options(nostack)
    );
}}
'''


if __name__ == '__main__':
    os.environ['MFIRST'] = '1'
    (HERE.parent / 'src' / 'ntt_neon_signed_asm.rs').write_text(
        '// Generated by gen/emit_signed.py.\nuse super::*;\n' + front() + tail())
