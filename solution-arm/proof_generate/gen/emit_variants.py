"""Writes ../src/ntt_neon_asm_var.rs: generator-parameter variants of the three generated passes, for
the post-proof on-hardware tuning run (`sms::tune_passes`). Diagnostic only; the proof uses
`ntt_neon_asm.rs`. Run `python3 emit_variants.py` here."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import emit

# (per, K, B, width, ls, v2); the first entry is the crown's setting (a sanity check: ~0% delta)
PC = [(6, 40, 28, 6, 2, False), (8, 40, 28, 6, 2, False), (12, 40, 28, 6, 2, False), (4, 40, 28, 6, 2, False),
      (3, 40, 28, 6, 2, False), (2, 40, 28, 6, 2, False), (24, 40, 28, 6, 2, False), (6, 24, 28, 6, 2, False),
      (6, 64, 28, 6, 2, False), (6, 8, 28, 6, 2, False), (6, 40, 26, 6, 2, False), (6, 40, 29, 6, 2, False),
      (6, 40, 28, 6, 1, False), (6, 40, 28, 6, 3, False), (6, 40, 28, 4, 2, False), (6, 40, 28, 8, 2, False)]
LUT = [(27, 12, 18, 6, 1, False), (27, 8, 18, 6, 1, False), (27, 16, 18, 6, 1, False), (27, 12, 16, 6, 1, False),
       (27, 12, 17, 6, 1, False), (27, 12, 18, 6, 2, False), (27, 12, 18, 4, 1, False), (9, 12, 18, 6, 1, False),
       (27, 12, 18, 5, 1, False), (27, 24, 18, 6, 1, False)]
# (U, K, B)
PD = [(12, 22, 29), (6, 22, 29), (9, 22, 29), (18, 22, 29), (12, 8, 29), (12, 16, 29), (12, 30, 29), (12, 22, 28),
      (12, 22, 27), (18, 22, 28), (9, 30, 29)]

def tag(p):
    return '_'.join(('v2' if x else 'm') if isinstance(x, bool) else str(x) for x in p)

out = ["// Generated by gen/emit_variants.py. Diagnostic only (post-proof tuning). Do not edit by hand.",
       "use super::*;", ""]
tables = {'PC': [], 'LUT': [], 'PD': []}
for i, p in enumerate(PC):
    name = f'pass_c_var{i}'
    try:
        out.append(emit.pass_c(*p, name=name)); tables['PC'].append((f'pc_{tag(p)}', name))
    except Exception as e:
        print('skip pc', p, e, file=sys.stderr)
for i, p in enumerate(LUT):
    name = f'pass_lut_var{i}'
    try:
        out.append(emit.pass_lut(*p, name=name)); tables['LUT'].append((f'lut_{tag(p)}', name))
    except Exception as e:
        print('skip lut', p, e, file=sys.stderr)
for i, p in enumerate(PD):
    name = f'pass_d_var{i}'
    try:
        out.append(emit.pass_d(*p, name=name)); tables['PD'].append((f'pd_{tag(p)}', name))
    except Exception as e:
        print('skip pd', p, e, file=sys.stderr)
out.append('pub type PassFn = unsafe fn(&mut [int16x8_t; N], &Kernel);')
out.append('pub type LutFn = unsafe fn(&[uint8x16_t; GROUPS], &mut [int16x8_t; N], &Kernel);')
out.append('pub static PC_VARIANTS: &[(&str, PassFn)] = &[' + ', '.join(f'("{t}", {n})' for t, n in tables['PC']) + '];')
out.append('pub static LUT_VARIANTS: &[(&str, LutFn)] = &[' + ', '.join(f'("{t}", {n})' for t, n in tables['LUT']) + '];')
out.append('pub static PD_VARIANTS: &[(&str, PassFn)] = &[' + ', '.join(f'("{t}", {n})' for t, n in tables['PD']) + '];')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'ntt_neon_asm_var.rs'), 'w').write('\n'.join(out) + '\n')
print({k: len(v) for k, v in tables.items()}, file=sys.stderr)
