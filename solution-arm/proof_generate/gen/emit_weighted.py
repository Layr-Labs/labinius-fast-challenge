"""Generate the SVE2 weighted nibble front. Run from any directory."""
from pathlib import Path

import gen_lut
import weighted_tables
from sched import Ins, allocate, schedule

# X0 uses two registers. All other indices have at most eight entries.
RAW = [16, 18, 19, 20, 21, 22]
WEIGHTED = [23, 24, 25, 26]


def build():
    ins = []
    for j in range(27):
        first = len(ins)

        def lookup(register, index, pair=False):
            dst = f"lookup{len(ins)}"
            table = f"z{register}.h, z{register + 1}.h" if pair else f"z{register}.h"
            ins.append(Ins("A", [dst], [index], f"tbl z{{d0}}.h, LB{table}RB, z{{s0}}.h"))
            return dst

        def arithmetic(op, a, b):
            dst = f"value{len(ins)}"
            ins.append(Ins("A", [dst], [a, b], f"{op} v{{d0}}.8h, v{{s0}}.8h, v{{s1}}.8h"))
            return dst

        def add(a, b):
            return arithmetic("add", a, b)

        def sub(a, b):
            return arithmetic("sub", a, b)

        raw, weighted = [], []
        for t, offset in enumerate((0, 81, 27, 108, 54, 135)):
            index = f"index{len(ins)}"
            ins.append(Ins("L", [index], [], gen_lut.ld1b(j + offset)))
            raw.append(lookup(RAW[t], index, t == 0 and j < 26))
            if t >= 2:
                weighted.append(lookup(WEIGHTED[t - 2], index))

        x0, y0, x1, y1, x2, y2 = raw
        wx1, wy1, wx2, wy2 = weighted
        a, b = add(x0, y0), sub(x0, y0)
        p0, p1 = add(y1, x2), add(wy1, wx2)
        q0, q1 = add(x1, y2), add(wx1, wy2)
        s0, s1 = add(p0, q0), add(p1, q1)
        d0, d1 = sub(p0, q0), sub(p1, q1)
        out = (add(a, s0), add(a, s1), sub(sub(a, s0), s1),
               sub(sub(b, d0), d1), add(b, d0), add(b, d1))
        for k, value in enumerate(out):
            ins.append(Ins("T", [], [value], f"str q{{s0}}, [XPTR, #{16 * (j + 27 * k)}]"))
        for step in ins[first:]:
            step.g = j
    return ins


def emit():
    # Keep all 11 nibble tables in registers. No twiddle register.
    reserved = tuple(range(16, 27))
    seq, _ = schedule(build(), skew=6, budget=21, reserve=0, cap=21, width=6, ls=1)
    asm, _ = allocate(seq, {}, set(), reserved=reserved)
    instructions = ["ptrue p7.h", "mov {n}, #4", "3:"]
    instructions += [f"ldp q{r}, q{r + 1}, [{{lut}}, #{16 * (r - 16)}]" for r in range(16, 26, 2)]
    instructions += ["ldr q26, [{lut}, #160]"]
    instructions += [gen_lut.base_names(a).replace("XPTR", "{x}").replace("LB", "{{").replace("RB", "}}") for a in asm]
    instructions += ["add {x}, {x}, #2592", "add {lut}, {lut}, #176", "subs {n}, {n}, #1", "b.ne 3b"]
    body = "\n".join(f'        "{a}",' for a in instructions)
    bases = "\n".join(
        f"        i{m} = in(reg) (idx.as_ptr() as *const u8).add({64 + 128 * m}),"
        for m in sorted(gen_lut.BASES)
    )
    clobbers = ", ".join(f'out("v{r}") _' for r in range(32))
    return f"""// Generated by gen/emit_weighted.py.
#[cfg(target_feature = "sve")]
use super::*;

/// Levels 0 to 3 for prime 9721. The table contains the cube-root products of
/// X1, Y1, X2 and Y2. Each extra lookup reuses its existing nibble index.
#[cfg(target_feature = "sve")]
#[inline(never)]
pub(super) unsafe fn pass_lut_weighted(idx: &[uint8x16_t; GROUPS], x: &mut [int16x8_t; N]) {{
    core::arch::asm!(
{body}
        x = inout(reg) x.as_mut_ptr() => _,
{bases}
        lut = inout(reg) LUT.as_ptr() => _,
        n = out(reg) _,
        {clobbers},
        out("p7") _,
        options(nostack)
    );
}}

#[cfg(any(test, target_feature = "sve"))]
#[path = "ntt_neon_weighted_tables.rs"]
mod tables;
#[cfg(any(test, target_feature = "sve"))]
pub(super) use tables::LUT;

#[cfg(test)]
#[path = "ntt_neon_weighted_tests.rs"]
mod tests;
"""


if __name__ == "__main__":
    src = Path(__file__).resolve().parents[1] / "src"
    (src / "ntt_neon_weighted.rs").write_text(emit())
    (src / "ntt_neon_weighted_tables.rs").write_text(weighted_tables.emit())
