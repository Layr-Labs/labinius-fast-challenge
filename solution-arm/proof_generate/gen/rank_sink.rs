// Generate the two row passes. Each vector holds four element pairs per column.
fn main() {
    use std::fmt::Write;
    let mut ops = vec![
        "ptrue p0.d".into(),
        "mov {slots}, #{slots_per_sweep}".into(),
        "2:".into(),
    ];
    for (pass, rows) in [0..3, 3..6].into_iter().enumerate() {
        let line = 3 + pass;
        for (offset, row) in rows.clone().enumerate() {
            for pair in 0..2 {
                let reg = 16 + 4 * offset + 2 * pair;
                let at = 64 * row + 32 * pair;
                if row != 0 {
                    ops.push(".if {fresh}".into());
                    ops.push(format!("movi v{reg}.16b, #0"));
                    ops.push(format!("movi v{}.16b, #0", reg + 1));
                    ops.push(".else".into());
                }
                ops.push(format!("ldp q{reg}, q{}, [{{acc}}, #{at}]", reg + 1));
                if row != 0 {
                    ops.push(".endif".into());
                }
            }
        }
        if pass == 0 {
            for q in 0..4 {
                ops.push(format!("movi v{}.16b, #0", 8 + q));
            }
        }
        ops.extend([
            "mov {zp}, {xs}".into(),
            "mov {kp}, {keys}".into(),
            "mov {n}, {groups}".into(),
            format!("{line}:"),
        ]);
        for t in 0..8 {
            if t == 4 {
                ops.push("add {zp}, {zp}, {xs_half}".into());
            }
            ops.push(format!("ldr q{t}, [{{zp}}, #({} * {{xs_stride}})]", t % 4));
        }
        if pass == 0 {
            for q in 0..4 {
                ops.push(format!("sdot z{}.d, z{q}.h, z{}.h", 8 + q, 4 + q));
            }
        }
        for (offset, row) in rows.clone().enumerate() {
            ops.push(format!("ld1rd {{z12.d}}, p0/z, [{{kp}}, #{}]", row * 16));
            ops.push(format!(
                "ld1rd {{z13.d}}, p0/z, [{{kp}}, #{}]",
                row * 16 + 8
            ));
            for q in 0..4 {
                ops.push(format!("add v14.8h, v12.8h, v{}.8h", 4 + q));
                ops.push(format!("add v15.8h, v13.8h, v{q}.8h"));
                ops.push(format!("sdot z{}.d, z14.h, z15.h", 16 + 4 * offset + q));
            }
        }
        ops.extend([
            "add {zp}, {zp}, {xs_half}".into(),
            "add {kp}, {kp}, {keys_tile}".into(),
            "subs {n}, {n}, #1".into(),
            format!("b.ne {line}b"),
        ]);
        for (offset, row) in rows.enumerate() {
            ops.push(format!(
                "ld1rsw {{z12.d}}, p0/z, [{{correction}}, #{}]",
                4 * row
            ));
            for q in 0..4 {
                let reg = 16 + 4 * offset + q;
                ops.push(format!("sub v{reg}.2d, v{reg}.2d, v{}.2d", 8 + q));
                ops.push(format!("sub v{reg}.2d, v{reg}.2d, v12.2d"));
            }
            for pair in 0..2 {
                let reg = 16 + 4 * offset + 2 * pair;
                ops.push(format!(
                    "stp q{reg}, q{}, [{{acc}}, #{}]",
                    reg + 1,
                    64 * row + 32 * pair
                ));
            }
        }
    }
    ops.extend(
        [
            "add {xs}, {xs}, #16",
            "add {keys}, {keys}, #96",
            "add {acc}, {acc}, #384",
            "add {correction}, {correction}, #24",
            "subs {slots}, {slots}, #1",
            "b.ne 2b",
        ]
        .map(str::to_owned),
    );

    let mut rust = String::from("core::arch::asm!(\n");
    for op in ops {
        let op = op
            .replace("{z12.d}", "{{z12.d}}")
            .replace("{z13.d}", "{{z13.d}}");
        writeln!(rust, "    {op:?},").unwrap();
    }
    rust.push_str("    xs = inout(reg) xs => _, keys = inout(reg) keys => _,\n");
    rust.push_str("    acc = inout(reg) acc => _, correction = inout(reg) correction => _,\n");
    rust.push_str("    groups = in(reg) groups, fresh = const FRESH as usize,\n");
    rust.push_str("    slots_per_sweep = const N, xs_stride = const N * 16,\n");
    rust.push_str(
        "    xs_half = in(reg) (LOCK / 2) * N * 16, keys_tile = in(reg) LOCK * ROWS * N * 2,\n",
    );
    rust.push_str("    zp = out(reg) _, kp = out(reg) _, n = out(reg) _, slots = out(reg) _,\n");
    for v in 0..28 {
        writeln!(rust, "    out(\"v{v}\") _,").unwrap();
    }
    rust.push_str("    out(\"p0\") _, options(nostack)\n)");
    println!("// Generated by gen/rank_sink.rs.\n{rust}");
}
