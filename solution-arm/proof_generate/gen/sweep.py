"""Regenerate ../src/ntt_neon_asm.rs with explicit schedule parameters.

Development tool for tuning the list-scheduler knobs of the three binary-transform
passes without editing `emit.py` defaults. Usage:

    python3 gen/sweep.py pd=U,K,B pc=per,K,B lut=per,K,B

Missing groups keep the checked-in defaults. Run from `gen/`.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
os.environ.setdefault('MFIRST', '1')
import emit  # noqa: E402  (imports write the default file; we overwrite it below)

DEFAULTS = {
    'pd': ('U', 12), 'pc': ('per', 6), 'lut': ('per', 27),
}
pd = dict(U=12, K=22, B=29)
pc = dict(per=6, K=40, B=28)
lut = dict(per=27, K=30, B=14)

args = dict(a.split('=', 1) for a in sys.argv[1:])
for group, spec in args.items():
    vals = [int(x) for x in spec.split(',')]
    target = {'pd': pd, 'pc': pc, 'lut': lut}[group]
    for key, v in zip(list(target), vals):
        target[key] = v

out = ("// Generated by gen/emit.py. Do not edit by hand.\nuse super::*;\n\n"
       + emit.pass_d(pd['U'], pd['K'], pd['B']) + "\n"
       + emit.pass_c(pc['per'], pc['K'], pc['B']) + "\n"
       + emit.pass_lut(lut['per'], lut['K'], lut['B']))
path = os.path.join(os.path.dirname(__file__), '..', 'src', 'ntt_neon_asm.rs')
open(path, 'w').write(out)
print(f"wrote {path}: pd={pd} pc={pc} lut={lut}")
