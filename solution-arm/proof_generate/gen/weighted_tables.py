def tables(node):
    exponents = (162, 1134, 810, 1782)
    tau = root(exponents[node] // 2)
    rho = root(exponents[node] // 6)
    eps, eps2 = root(648), root(1296)
    coefficients = (1, tau, rho, rho * tau, rho * rho, rho * rho * tau,
                    eps * rho, eps * rho * tau, eps2 * rho * rho, eps2 * rho * rho * tau)
    w = root(324 if node < 2 else 1620)
    t = root(162 if node < 2 else 810)
    sign = 1 if node % 2 else -1
    inputs = [
        -((pattern >> 0) & 1) - w * ((pattern >> 2) & 1)
        + sign * (t * ((pattern >> 1) & 1) + root(486) * ((pattern >> 3) & 1))
        for pattern in range(16)
    ]
    rows = []
    for i, (factor, (negative, positive)) in enumerate(zip(coefficients, SHIFTS[node])):
        table = [centered(x * factor * QUARTER_SCALE[node]) + P * (((positive >> j) & 1) - ((negative >> j) & 1))
                 for j, x in enumerate(inputs[:16 if i == 0 else 8])]
        rows.extend(table[j:j + 8] for j in range(0, len(table), 8))
    return rows


def emit():
    lines = [
        "// Generated by gen/emit_weighted.py from gen/weighted_tables.py.",
        "#[cfg(test)]",
        f"pub(in super::super) const QUARTER_SCALE: [i32; 4] = {list(QUARTER_SCALE)};",
        f"pub(in super::super) const QUARTER_INVERSE: [i64; 4] = {[pow(s, -1, P) for s in QUARTER_SCALE]};",
        "pub(in super::super) static LUT: [[[i16; 8]; 11]; 4] = [",
    ]
    for node in range(4):
        lines.append("    [")
        for table in tables(node):
            lines.append(f"        {table},")
        lines.append("    ],")
    lines.append("];")
    return "\n".join(lines) + "\n"
